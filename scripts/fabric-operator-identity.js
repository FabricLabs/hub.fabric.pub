'use strict';

/**
 * Optional on-disk operator identity for local automation (gitignored).
 * Prefer FABRIC_XPRV / FABRIC_SEED in the process environment for production.
 *
 * Commands:
 *   init              — create local/fabric-operator-identity.json
 *   emit-hub-config   — write assets/config.local.js (browser bootstrap, local only)
 *   print-shell-export — stdout `export FABRIC_XPRV=…`
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const IDENTITY_PATH = path.join(ROOT, 'local', 'fabric-operator-identity.json');
/** @private legacy filename still read if present */
const LEGACY_IDENTITY_PATH = path.join(ROOT, 'local', 'cursor-agent-fabric-identity.json');
const ASSETS_CONFIG = path.join(ROOT, 'assets', 'config.local.js');

function readJson (p) {
  return JSON.parse(fs.readFileSync(p, 'utf8'));
}

function resolveIdentityPath (preferWrite = false) {
  if (preferWrite) return IDENTITY_PATH;
  if (fs.existsSync(IDENTITY_PATH)) return IDENTITY_PATH;
  if (fs.existsSync(LEGACY_IDENTITY_PATH)) return LEGACY_IDENTITY_PATH;
  return IDENTITY_PATH;
}

function ensureLocalDir () {
  const dir = path.join(ROOT, 'local');
  if (!fs.existsSync(dir)) fs.mkdirSync(dir, { recursive: true });
}

function cmdInit (force) {
  ensureLocalDir();
  const dest = IDENTITY_PATH;
  if (fs.existsSync(dest) && !force) {
    console.error('[operator-identity] Already exists:', dest);
    console.error('                   Pass --force to replace (destroys previous mnemonic on disk).');
    process.exit(1);
  }
  const bip39 = require('@fabric/core/functions/bip39');
  const Identity = require('@fabric/core/types/identity');
  const mnemonic = bip39.generateMnemonic(128);
  const ident = new Identity({ seed: mnemonic });
  const xprv = ident.key && ident.key.xprv;
  const xpub = ident.key && ident.key.xpub;
  if (!xprv || !xpub) {
    console.error('[operator-identity] Key derivation failed');
    process.exit(1);
  }
  const payload = {
    version: 1,
    purpose: 'Local Fabric operator identity — hot wallet; never commit; share via FABRIC_XPRV across Hub and applications.',
    createdAt: new Date().toISOString(),
    mnemonic,
    fabricId: String(ident.id),
    xpub,
    xprv
  };
  fs.writeFileSync(dest, JSON.stringify(payload, null, 2) + '\n', { mode: 0o600 });
  console.log('[operator-identity] Wrote', dest);
  console.log('[operator-identity] fabricId:', payload.fabricId);
  console.log('[operator-identity] Prefer: eval "$(npm run -s operator-identity:print-env)"');
}

function cmdEmitHubConfig () {
  const src = resolveIdentityPath();
  if (!fs.existsSync(src)) {
    console.error('[operator-identity] Missing', src, '— run: npm run operator-identity:init');
    process.exit(1);
  }
  const data = readJson(src);
  const phrase = String(data.mnemonic || '').trim();
  if (!phrase) {
    console.error('[operator-identity] JSON missing mnemonic');
    process.exit(1);
  }
  const edge = process.env.FABRIC_EDGE_AUTHORITY
    ? String(process.env.FABRIC_EDGE_AUTHORITY).trim()
    : 'http://localhost:8080';
  const body = `'use strict';
/* Auto-generated by scripts/fabric-operator-identity.js emit-hub-config — do not commit if it contains a seed. */
window.FABRIC_EDGE_AUTHORITY = ${JSON.stringify(edge)};
window.FABRIC_DEV_BROWSER_SEED = ${JSON.stringify(phrase)};
window.FABRIC_DEV_BROWSER_IDENTITY = 'force';
`;
  fs.writeFileSync(ASSETS_CONFIG, body, { mode: 0o600 });
  console.log('[operator-identity] Wrote', ASSETS_CONFIG);
}

function cmdPrintShellExport () {
  const src = resolveIdentityPath();
  if (!fs.existsSync(src)) {
    console.error('[operator-identity] Missing', src);
    process.exit(1);
  }
  const data = readJson(src);
  const xprv = String(data.xprv || '').trim();
  const phrase = String(data.mnemonic || '').trim();
  if (xprv.startsWith('xprv') || xprv.startsWith('tprv')) {
    process.stdout.write(`export FABRIC_XPRV=${JSON.stringify(xprv)}\n`);
    return;
  }
  if (!phrase) process.exit(1);
  try {
    const Key = require('@fabric/core/types/key');
    const key = new Key({ mnemonic: phrase });
    process.stdout.write(`export FABRIC_XPRV=${JSON.stringify(key.xprv)}\n`);
  } catch (_) {
    process.stdout.write(`export FABRIC_SEED=${JSON.stringify(phrase)}\n`);
  }
}

const arg = (process.argv[2] || '').toLowerCase();
const force = process.argv.includes('--force');

if (arg === 'init') {
  cmdInit(force);
} else if (arg === 'emit-hub-config' || arg === 'emit') {
  cmdEmitHubConfig();
} else if (arg === 'print-shell-export' || arg === 'print-env') {
  cmdPrintShellExport();
} else {
  console.error(`Usage:
  node scripts/fabric-operator-identity.js init [--force]
  node scripts/fabric-operator-identity.js emit-hub-config
  node scripts/fabric-operator-identity.js print-shell-export`);
  process.exit(1);
}
