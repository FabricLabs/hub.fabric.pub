'use strict';

/**
 * Canonical on-disk identity for the Cursor / automation agent (Eric's workspace).
 * - `init` — create local/cursor-agent-fabric-identity.json (BIP39 + Fabric id/xpub/xprv).
 * - `emit-hub-config` — write assets/config.local.js for Hub browser bootstrap (FABRIC_DEV_*).
 * - `print-shell-export` — stdout FABRIC_MNEMONIC=… for Sensemaker / shell (redirect to file; never commit).
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const IDENTITY_PATH = path.join(ROOT, 'local', 'cursor-agent-fabric-identity.json');
const ASSETS_CONFIG = path.join(ROOT, 'assets', 'config.local.js');
const EXAMPLE_CONFIG = path.join(ROOT, 'assets', 'config.local.example.js');

function readJson (p) {
  return JSON.parse(fs.readFileSync(p, 'utf8'));
}

function ensureLocalDir () {
  const dir = path.join(ROOT, 'local');
  if (!fs.existsSync(dir)) fs.mkdirSync(dir, { recursive: true });
}

function cmdInit (force) {
  ensureLocalDir();
  if (fs.existsSync(IDENTITY_PATH) && !force) {
    console.error('[cursor-agent] Identity already exists:', IDENTITY_PATH);
    console.error('            Pass --force to replace (destroys previous mnemonic on disk).');
    process.exit(1);
  }
  const bip39 = require('@fabric/core/functions/bip39');
  const Identity = require('@fabric/core/types/identity');
  const mnemonic = bip39.generateMnemonic(128);
  const ident = new Identity({ seed: mnemonic });
  const xprv = ident.key && ident.key.xprv;
  const xpub = ident.key && ident.key.xpub;
  if (!xprv || !xpub) {
    console.error('[cursor-agent] Key derivation failed');
    process.exit(1);
  }
  const payload = {
    version: 1,
    purpose: 'Cursor agent Fabric identity — hot wallet; never commit; use across Hub / Sensemaker / Fabric tooling.',
    createdAt: new Date().toISOString(),
    mnemonic,
    fabricId: String(ident.id),
    xpub,
    xprv
  };
  fs.writeFileSync(IDENTITY_PATH, JSON.stringify(payload, null, 2) + '\n', { mode: 0o600 });
  console.log('[cursor-agent] Wrote', IDENTITY_PATH);
  console.log('[cursor-agent] fabricId:', payload.fabricId);
}

function cmdEmitHubConfig () {
  if (!fs.existsSync(IDENTITY_PATH)) {
    console.error('[cursor-agent] Missing', IDENTITY_PATH, '— run: npm run cursor-agent:init');
    process.exit(1);
  }
  const data = readJson(IDENTITY_PATH);
  const phrase = String(data.mnemonic || '').trim();
  if (!phrase) {
    console.error('[cursor-agent] JSON missing mnemonic');
    process.exit(1);
  }
  const edge = process.env.FABRIC_EDGE_AUTHORITY
    ? String(process.env.FABRIC_EDGE_AUTHORITY).trim()
    : 'http://localhost:8080';
  const body = `'use strict';
/* Auto-generated by scripts/cursor-agent-fabric-identity.js emit-hub-config — do not commit if it contains a seed. */
window.FABRIC_EDGE_AUTHORITY = ${JSON.stringify(edge)};
window.FABRIC_DEV_BROWSER_SEED = ${JSON.stringify(phrase)};
window.FABRIC_DEV_BROWSER_IDENTITY = 'force';
`;
  fs.writeFileSync(ASSETS_CONFIG, body, { mode: 0o600 });
  console.log('[cursor-agent] Wrote', ASSETS_CONFIG);
}

function cmdPrintShellExport () {
  if (!fs.existsSync(IDENTITY_PATH)) {
    console.error('[cursor-agent] Missing', IDENTITY_PATH);
    process.exit(1);
  }
  const data = readJson(IDENTITY_PATH);
  const phrase = String(data.mnemonic || '').trim();
  if (!phrase) process.exit(1);
  process.stdout.write(`export FABRIC_MNEMONIC=${JSON.stringify(phrase)}\n`);
}

const arg = (process.argv[2] || '').toLowerCase();
const force = process.argv.includes('--force');

if (arg === 'init') {
  cmdInit(force);
} else if (arg === 'emit-hub-config' || arg === 'emit') {
  cmdEmitHubConfig();
} else if (arg === 'print-shell-export' || arg === 'print-env') {
  cmdPrintShellExport();
} else {
  console.error(`Usage:
  node scripts/cursor-agent-fabric-identity.js init [--force]
  node scripts/cursor-agent-fabric-identity.js emit-hub-config
  node scripts/cursor-agent-fabric-identity.js print-shell-export`);
  process.exit(1);
}
